#!/usr/bin/env node
/**
 * Build training-event pages and catalog cards from content/events/*.json.
 * Usage: npm run build:events
 */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const { SLUG_RE, renderCatalog, renderEventPage } = require('../lib/event-pages');

const root = path.join(__dirname, '..');
const eventsDir = path.join(root, 'content/events');
const generatedMark = /generated by build:events from content\/events\/([a-z0-9-]+)\.json/;

const catalogs = [
  { file: 'live-events.html', surface: 'events', variant: 'courses' },
  { file: 'index.html', surface: 'home', variant: 'home' },
];

function loadEvents() {
  if (!fs.existsSync(eventsDir)) {
    throw new Error('Missing content/events');
  }

  const events = [];
  const seen = new Set();

  for (const name of fs.readdirSync(eventsDir).sort()) {
    if (!name.endsWith('.json') || name.startsWith('_')) continue;
    const event = JSON.parse(fs.readFileSync(path.join(eventsDir, name), 'utf8'));
    if (!SLUG_RE.test(event.slug || '')) {
      throw new Error(`${name} has an invalid slug`);
    }
    if (name !== `${event.slug}.json`) {
      throw new Error(`${name} must be named ${event.slug}.json`);
    }
    if (seen.has(event.slug)) throw new Error(`Duplicate slug ${event.slug}`);
    seen.add(event.slug);
    if (!event.catalog || !event.catalog.title) {
      throw new Error(`${name} needs catalog.title`);
    }
    events.push(event);
  }

  return events;
}

function writePages(events) {
  const generated = new Set();
  for (const event of events) {
    if (event.pageMode !== 'generated') continue;
    const filePath = path.join(root, `${event.slug}.html`);
    fs.writeFileSync(filePath, renderEventPage(event));
    generated.add(event.slug);
    console.log('wrote', `${event.slug}.html`);
  }
  return generated;
}

function deleteOrphans(generated) {
  for (const name of fs.readdirSync(root)) {
    if (!name.endsWith('.html')) continue;
    const filePath = path.join(root, name);
    if (!fs.statSync(filePath).isFile()) continue;
    const text = fs.readFileSync(filePath, 'utf8');
    const match = text.match(generatedMark);
    if (!match || generated.has(match[1])) continue;
    fs.unlinkSync(filePath);
    console.log('removed', name);
  }
}

function injectCatalogs(events) {
  const start = '<!-- LINKPRO_EVENTS_START -->';
  const end = '<!-- LINKPRO_EVENTS_END -->';

  for (const catalog of catalogs) {
    const filePath = path.join(root, catalog.file);
    const content = fs.readFileSync(filePath, 'utf8');
    const startAt = content.indexOf(start);
    const endAt = content.indexOf(end);
    if (startAt === -1 || endAt === -1 || endAt < startAt) {
      throw new Error(`Missing event markers in ${catalog.file}`);
    }
    const cards = renderCatalog(events, catalog.surface, catalog.variant);
    const next = `${content.slice(0, startAt + start.length)}\n${cards}\n${content.slice(endAt)}`;
    fs.writeFileSync(filePath, next);
    console.log('catalog', catalog.file);
  }
}

function runScript(file) {
  const result = spawnSync(process.execPath, [path.join(__dirname, file)], { stdio: 'inherit' });
  if (result.status !== 0) process.exit(result.status || 1);
}

function main() {
  const events = loadEvents();
  const generated = writePages(events);
  deleteOrphans(generated);
  injectCatalogs(events);
  runScript('build-nav.js');
  runScript('build-analytics.js');
  console.log('build:events complete');
}

if (require.main === module) main();

module.exports = { loadEvents };
